"""Builds MAP.md: every project and named folder in the repository with one line saying what it is.

The line is the first sentence of the folder's own README, so the map cannot say something the folder does not. A folder with no README is listed as
"(no README)": the map shows the gap instead of hiding it, and the check fails it. Which folders are named, and how the map is grouped, is the repository's
`doc-checks.json` ("map"); every folder with a project file in it is listed without being named.
"""

import pathlib
import re

IGNORED_PARTS = {'bin', 'obj', 'node_modules'}
DEFAULT_GROUPS = [('src', 'The source'), ('tests', 'The tests')]
REST = 'Operations and documentation'
NO_README = '(no README)'
NO_TEXT = '(the README has no text)'
COMMAND = 'python tools/doc_checks/run.py map'


def first_sentence(text):
    """The first sentence of the first paragraph under the heading, with quote marks, bold and link targets removed."""
    lines = text.replace('\r\n', '\n').split('\n')
    body = []
    started = False
    for line in lines:
        if not started:
            if line.startswith('#') or not line.strip():
                continue
            started = True
        if not line.strip():
            break
        body.append(re.sub(r'^>\s?', '', line).strip())
    paragraph = ' '.join(body)
    paragraph = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', paragraph).replace('**', '')
    match = re.match(r'(.+?[.!?])(\s|$)', paragraph)
    return match.group(1) if match else paragraph


def folders_needing_a_readme(root, named_folders):
    """Every folder with a project file in it, and the named folders that exist, as paths relative to the root."""
    found = {
        project.parent.relative_to(root).as_posix()
        for project in root.rglob('*.csproj')
        if not IGNORED_PARTS.intersection(project.relative_to(root).parts)
    }
    found.update(folder for folder in named_folders if (root / folder).is_dir())
    return sorted(found)


def describe(root, folder):
    readme = root / folder / 'README.md'
    if not readme.exists():
        return NO_README
    sentence = first_sentence(readme.read_text(encoding='utf-8'))
    return sentence.replace('|', '\\|') if sentence else NO_TEXT


def table(rows):
    """A Markdown table padded the way Prettier pads it, so the file passes `prettier --check` as generated."""
    header = ['Folder', 'What it is']
    width = [max(len(row[column]) for row in [header, *rows]) for column in range(2)]
    lines = ['| ' + ' | '.join(cell.ljust(width[column]) for column, cell in enumerate(row)) + ' |' for row in [header, *rows]]
    lines.insert(1, '| ' + ' | '.join('-' * width[column] for column in range(2)) + ' |')
    return '\n'.join(lines)


def build_map(root, named_folders, groups=DEFAULT_GROUPS, command=COMMAND):
    """The text of MAP.md. A folder whose first part is a group's prefix is listed in that group; the rest are listed last."""
    root = pathlib.Path(root)
    folders = folders_needing_a_readme(root, named_folders)
    prefixes = {prefix for prefix, _ in groups}
    sections = [
        '# Repository map',
        '',
        f'Every project and top-level folder, with the first sentence of its own README. Generated by `{command}`:',
        "do not edit by hand; change the folder's README and run the script. A test fails when this file is out of date.",
    ]
    for prefix, title in [*groups, ('', REST)]:
        members = [folder for folder in folders if (folder.split('/')[0] == prefix if prefix else folder.split('/')[0] not in prefixes)]
        if members:
            rows = [[f'`{folder}`', describe(root, folder)] for folder in members]
            sections += ['', f'## {title}', '', table(rows)]
    return '\n'.join(sections) + '\n'


def write_map(root, named_folders, groups=DEFAULT_GROUPS, command=COMMAND):
    target = pathlib.Path(root) / 'MAP.md'
    target.write_text(build_map(root, named_folders, groups, command), encoding='utf-8', newline='\n')
    return target


def map_problems(root, named_folders, groups=DEFAULT_GROUPS, command=COMMAND):
    """Whether MAP.md is what the folders say, and which folders have no README."""
    root = pathlib.Path(root)
    target = root / 'MAP.md'
    current = build_map(root, named_folders, groups, command)
    committed = target.read_text(encoding='utf-8').replace('\r\n', '\n') if target.exists() else ''
    found = [] if committed == current else [f'MAP.md is out of date: run `{command}` and commit it']
    found += [
        f'{folder} has no README.md: write its five lines'
        for folder in folders_needing_a_readme(root, named_folders)
        if not (root / folder / 'README.md').exists()
    ]
    return found
