using Backplane.Conventions.Rules;

namespace Backplane.Conventions.Tests;

/// <summary>The suppression rule, proved on samples that break it and samples that do not.</summary>
[TestFixture]
public class SuppressionRuleTests
{
    [Test]
    public void AnUnexplainedPragma_IsFound_AndAnExplainedOneIsNot()
    {
        SourceSet sample = SourceSet.OfText("#pragma warning disable CA1822\nclass First { }\n#pragma warning disable CA1051 // fields are the JSON shape clients send\nclass Second { }\n");

        Assert.That(SuppressionRule.Violations(sample), Has.Count.EqualTo(1), "only the pragma with no reason after it is reported");
    }

    [Test]
    public void ARestoreIsNotASuppression()
    {
        SourceSet sample = SourceSet.OfText("#pragma warning restore CA1822\nclass First { }\n");

        Assert.That(SuppressionRule.Violations(sample), Is.Empty, "only a disable switches a rule off");
    }

    [Test]
    public void ASuppressMessage_OrAnExclusionFromCoverage_WithoutAJustification_IsFound()
    {
        SourceSet sample = SourceSet.OfText(
            "class Sample { [SuppressMessage(\"Naming\", \"CA1720\")] int a; [SuppressMessage(\"Naming\", \"CA1720\", Justification = \"The IRS name, and the JSON value.\")] int b; "
            + "[ExcludeFromCodeCoverage] int c; [ExcludeFromCodeCoverage(Justification = \"Generated by the framework.\")] int d; "
            + "[ExcludeFromCodeCoverage(Justification = \"ok\")] int e; }");

        Assert.That(SuppressionRule.Violations(sample), Has.Count.EqualTo(3), "no Justification, or one too short to be a reason, is reported");
    }
}
